flags=collections.defaultdict(list)
for ep,info in d['eps'].items():
    o,ut=ordr[ep]
    for it in info['items']:
        for fld in ['q','o','h','v']:
            t=it[fld]
            if not t: continue
            if fld=='v': t=re.sub(r'돌리기 ↻|돌리기','',t)
            for rx,co,name in C:
                if co>o and re.search(rx,t):
                    flags[(ep,name)].append((it['i'],fld,t[:110]))
for (ep,name),L in sorted(flags.items(),key=lambda x:x[0]):
    o,ut=ordr[ep]; print(f"{ep} [{ut} / {d['eps'][ep]['n'][0]}] ⟶ {name} ({len(L)}건): #{L[0][0]} {L[0][1]}: {L[0][2]}")
print(len(flags))
