d=json.load(open('analysis/cur.json'))
ordr={}
for u in d['units']:
    m=re.match(r'(\d)-(\d)',u['t']); o=int(m.group(1))*10+int(m.group(2))
    for e in u['eps']: ordr[e]=(o,u['t'])
